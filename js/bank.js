  function parseCSVRows(text) {
    const rows = []; let row = [], cur = '', q = false;
    text = text.replace(/^﻿/, '');
    for (let i = 0; i < text.length; i++) {
      const ch = text[i];
      if (q) { if (ch === '"') { if (text[i + 1] === '"') { cur += '"'; i++; } else q = false; } else cur += ch; }
      else if (ch === '"') q = true;
      else if (ch === ',') { row.push(cur); cur = ''; }
      else if (ch === '\n' || ch === '\r') { if (ch === '\r' && text[i + 1] === '\n') i++; row.push(cur); rows.push(row); row = []; cur = ''; }
      else cur += ch;
    }
    if (cur.length || row.length) { row.push(cur); rows.push(row); }
    return rows.filter(r => r.some(c => c.trim()));
  }
  function parseCSV(text) {
    const rows = parseCSVRows(text); const valid = [], errors = [];
    rows.forEach((r, i) => {
      const cells = r.map(c => c.trim());
      if (i === 0 && /คำถาม|question/i.test(cells[0])) return; // หัวตาราง
      if (cells.length < 6) { errors.push({ line: i + 1, raw: r.join(','), message: 'ต้องมีอย่างน้อย 6 คอลัมน์: คำถาม,A,B,C,D,เฉลย' }); return; }
      const [text, a, b, c, d, ans, explain = ''] = cells;
      const correct = L2I[ans.toLowerCase()];
      if (!text || !a || !b || !c || !d || correct == null) { errors.push({ line: i + 1, raw: r.join(','), message: 'ข้อมูลไม่ครบหรือเฉลยไม่ใช่ A-D' }); return; }
      valid.push({ text, a, b, c, d, correct, explain });
    });
    return { valid, errors };
  }
  function toCSV(set) {
    const esc = (s) => '"' + String(s == null ? '' : s).replace(/"/g, '""') + '"';
    const lines = ['คำถาม,A,B,C,D,เฉลย,คำอธิบาย'];
    for (const q of set.questions) lines.push([q.text, q.a, q.b, q.c, q.d, 'ABCD'[q.correct], q.explain || ''].map(esc).join(','));
    return '﻿' + lines.join('\r\n');
  }
  function toBulk(set) { return set.questions.map(q => [set.name, q.text, q.a, q.b, q.c, q.d, 'ABCD'[q.correct], q.explain || ''].join('|')).join('\n'); }

